"""Builds intro/europe-data.js: a dot-matrix map of Europe, EU capitals and a graticule.

Source data: Natural Earth 1:50m countries (public domain) via the `world-atlas` npm package.
Usage: python3 tools/build_map.py path/to/countries-50m.json
"""
import json
import math
import sys

import numpy as np
from shapely.geometry import Polygon, MultiPolygon, box
from shapely.ops import transform, unary_union
from shapely.prepared import prep

R = 6371000.0
LON0, LAT0 = 10.0, 52.0          # ETRS89-LAEA style centre (EPSG:3035)
HUB = (4.35, 50.85)              # Brussels sits at the frame centre
PX_PER_M = 0.000292              # base map scale (px per metre)
SPACING_PX = 13.0                # dot pitch on screen at zoom 1

EU = {40, 56, 100, 191, 196, 203, 208, 233, 246, 250, 276, 300, 348, 372, 380,
      428, 440, 442, 470, 528, 616, 620, 642, 703, 705, 724, 752}
HUNGARY = 348

CAPITALS = [
    ("brussels", 4.35, 50.85), ("budapest", 19.04, 47.50), ("strasbourg", 7.75, 48.58),
    ("luxembourg", 6.13, 49.61), ("vienna", 16.37, 48.21), ("berlin", 13.40, 52.52),
    ("paris", 2.35, 48.86), ("amsterdam", 4.90, 52.37), ("rome", 12.50, 41.90),
    ("madrid", -3.70, 40.42), ("lisbon", -9.14, 38.72), ("dublin", -6.26, 53.35),
    ("copenhagen", 12.57, 55.68), ("stockholm", 18.07, 59.33), ("helsinki", 24.94, 60.17),
    ("tallinn", 24.75, 59.44), ("riga", 24.11, 56.95), ("vilnius", 25.28, 54.69),
    ("warsaw", 21.01, 52.23), ("prague", 14.42, 50.08), ("bratislava", 17.11, 48.15),
    ("ljubljana", 14.51, 46.06), ("zagreb", 15.98, 45.81), ("bucharest", 26.10, 44.43),
    ("sofia", 23.32, 42.70), ("athens", 23.73, 37.98), ("valletta", 14.51, 35.90),
    ("nicosia", 33.38, 35.17),
]


def laea(lon, lat):
    lam, phi = np.radians(lon) - math.radians(LON0), np.radians(lat)
    p0 = math.radians(LAT0)
    k = np.sqrt(2.0 / (1.0 + math.sin(p0) * np.sin(phi) + math.cos(p0) * np.cos(phi) * np.cos(lam)))
    x = R * k * np.cos(phi) * np.sin(lam)
    y = R * k * (math.cos(p0) * np.sin(phi) - math.sin(p0) * np.cos(phi) * np.cos(lam))
    return x, y


HX, HY = laea(*HUB)


def to_screen(lon, lat):
    x, y = laea(lon, lat)
    return (x - HX) * PX_PER_M, -(y - HY) * PX_PER_M


def decode_topology(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        a = np.cumsum(np.array(arc, dtype=float), axis=0)
        arcs.append(np.column_stack([a[:, 0] * sx + tx, a[:, 1] * sy + ty]))

    def ring(indices):
        pts = []
        for i in indices:
            seg = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(seg if not pts else seg[1:])
        return pts

    countries = {}
    for g in topo["objects"]["countries"]["geometries"]:
        if g.get("type") not in ("Polygon", "MultiPolygon") or "id" not in g:
            continue
        polys = [g["arcs"]] if g["type"] == "Polygon" else g["arcs"]
        shapes = []
        for p in polys:
            rings = [ring(r) for r in p]
            if len(rings[0]) >= 4:
                shapes.append(Polygon(rings[0], rings[1:]).buffer(0))
        countries[int(g["id"])] = unary_union(shapes)
    return countries


def main(path):
    with open(path) as f:
        countries = decode_topology(json.load(f))

    window = box(-30, 25, 60, 75)
    proj = lambda x, y, z=None: to_screen(np.asarray(x), np.asarray(y))
    shapes = {}
    for cid, geom in countries.items():
        g = geom.intersection(window)
        if not g.is_empty:
            shapes[cid] = prep(transform(proj, g))

    dots = []
    half_w, half_h = 900, 1150
    ys = np.arange(-half_h, half_h, SPACING_PX)
    xs = np.arange(-half_w, half_w, SPACING_PX)
    from shapely.geometry import Point
    for y in ys:
        for x in xs:
            pt = Point(x, y)
            for cid, g in shapes.items():
                if g.contains(pt):
                    cls = 2 if cid == HUNGARY else (1 if cid in EU else 0)
                    dots += [round(float(x), 1), round(float(y), 1), cls]
                    break

    caps = []
    for name, lon, lat in CAPITALS:
        x, y = to_screen(lon, lat)
        caps.append({"id": name, "x": round(float(x), 1), "y": round(float(y), 1)})

    grat = []
    for lat in (40, 50, 60, 70):
        lons = np.linspace(-30, 50, 81)
        x, y = to_screen(lons, np.full_like(lons, lat))
        grat.append([round(float(v), 1) for pair in zip(x, y) for v in pair])
    for lon in range(-20, 50, 10):
        lats = np.linspace(30, 75, 46)
        x, y = to_screen(np.full_like(lats, lon), lats)
        grat.append([round(float(v), 1) for pair in zip(x, y) for v in pair])

    out = "intro/europe-data.js"
    with open(out, "w") as f:
        f.write("// Generated by tools/build_map.py from Natural Earth 1:50m (public domain). Do not edit.\n")
        f.write("// Coordinates are screen pixels at zoom 1, relative to Brussels.\n")
        f.write("window.EUROPE = {\n")
        f.write(f"  dots: [{','.join(map(str, dots))}],\n")
        f.write(f"  capitals: {json.dumps(caps, separators=(',', ':'))},\n")
        f.write(f"  graticule: {json.dumps(grat, separators=(',', ':'))}\n")
        f.write("};\n")
    print(f"{len(dots) // 3} dots, {len(caps)} capitals -> {out}")
    for c in caps:
        print(f"  {c['id']:<11} {c['x']:8.1f} {c['y']:8.1f}")


if __name__ == "__main__":
    main(sys.argv[1])

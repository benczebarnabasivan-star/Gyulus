import type { Metadata } from 'next';
import { siteConfig } from '@/config/site';
import type { Video } from '@/types';

/** Build a fully-resolved absolute URL for the site. */
export function absoluteUrl(path = ''): string {
  return `${siteConfig.url}${path.startsWith('/') ? path : `/${path}`}`;
}

/** Default metadata used by the root layout. */
export function buildDefaultMetadata(): Metadata {
  return {
    metadataBase: new URL(siteConfig.url),
    title: {
      default: `${siteConfig.shortName} — ${siteConfig.tagline}`,
      template: `%s · ${siteConfig.shortName}`,
    },
    description: siteConfig.description,
    keywords: [...siteConfig.keywords],
    applicationName: siteConfig.name,
    authors: [{ name: 'Vadász Gyula rajongók' }],
    creator: siteConfig.shortName,
    alternates: { canonical: '/' },
    openGraph: {
      type: 'website',
      locale: siteConfig.locale,
      url: siteConfig.url,
      siteName: siteConfig.name,
      title: `${siteConfig.shortName} — ${siteConfig.tagline}`,
      description: siteConfig.description,
      // OG/Twitter images are generated by app/opengraph-image.tsx and
      // app/twitter-image.tsx (file conventions), so no static path needed.
    },
    twitter: {
      card: 'summary_large_image',
      title: `${siteConfig.shortName} — ${siteConfig.tagline}`,
      description: siteConfig.description,
    },
    robots: {
      index: true,
      follow: true,
      googleBot: { index: true, follow: true, 'max-image-preview': 'large' },
    },
  };
}

/** JSON-LD structured data for a single video (schema.org/VideoObject). */
export function videoJsonLd(video: Video) {
  return {
    '@context': 'https://schema.org',
    '@type': 'VideoObject',
    name: video.caption,
    description: video.caption,
    thumbnailUrl: [video.thumbnailUrl],
    uploadDate: video.uploadedAt,
    contentUrl: video.url,
    embedUrl: video.url,
    interactionStatistic: [
      {
        '@type': 'InteractionCounter',
        interactionType: { '@type': 'WatchAction' },
        userInteractionCount: video.stats.views,
      },
      {
        '@type': 'InteractionCounter',
        interactionType: { '@type': 'LikeAction' },
        userInteractionCount: video.stats.likes,
      },
    ],
    creator: {
      '@type': 'Person',
      name: 'Vadász Gyula',
      url: siteConfig.tiktokUrl,
    },
  };
}

/** JSON-LD for the site/person profile. */
export function personJsonLd() {
  return {
    '@context': 'https://schema.org',
    '@type': 'ProfilePage',
    mainEntity: {
      '@type': 'Person',
      name: 'Vadász Gyula',
      alternateName: '@vadasz_gyula',
      url: siteConfig.tiktokUrl,
      description: siteConfig.description,
    },
  };
}

import type { Billing, Festival, FestivalDay, SetSlot } from './types';

/**
 * ─────────────────────────────────────────────────────────────────────────
 * SAMPLE LINEUP DATA
 *
 * Festival names, cities and approximate seasons are real; the day-by-day
 * lineups and set times below are illustrative sample data written for this
 * demo. They are NOT announced schedules and must not be read as such — the
 * UI labels every schedule accordingly.
 *
 * To run on real data, replace `getFestivals()` in `./index.ts` with a call to
 * a ticketing/listings provider (Ticketmaster Discovery, Songkick, Bandsintown)
 * that returns the same `Festival[]` shape.
 * ─────────────────────────────────────────────────────────────────────────
 */

type RawSlot = [artist: string, stage: string, start: string, end: string, billing?: Billing];

function buildDay(slug: string, date: string, raw: RawSlot[]): FestivalDay {
  const slots: SetSlot[] = raw.map(([artist, stage, start, end, billing = 'support'], i) => ({
    id: `${slug}-${date}-${i}`,
    artist,
    stage,
    start,
    end,
    billing,
  }));
  return { date, slots };
}

type RawFestival = Omit<Festival, 'days'> & { rawDays: [string, RawSlot[]][] };

function build(f: RawFestival): Festival {
  const { rawDays, ...rest } = f;
  return { ...rest, days: rawDays.map(([date, slots]) => buildDay(f.slug, date, slots)) };
}

